let current = 'en';

export function setUiLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current === 'jp' ? 'ja' : current;
  document.documentElement.dataset.uiLang = current;
  applyStatic();
}

export function getUiLang() { return current; }

/** Translate a key. */
export function t(key) {
  return STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
}

/** Label for a content language, in the current UI language. */
export function langLabel(id) {
  const l = CONTENT_LANGS.find((c) => c.id === id);
  return l ? (l.label[current] ?? l.label.en) : id;
}

export function langShort(id) {
  return CONTENT_LANGS.find((c) => c.id === id)?.short ?? id.toUpperCase();
}

/** Re-render every [data-i18n] node. Called on every language change. */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = t(el.dataset.i18n);
    if (v.includes('<')) el.innerHTML = v; else el.textContent = v;
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(',').forEach((pair) => {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr.trim(), t(key.trim()));
    });
  });
}
